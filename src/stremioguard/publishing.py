# Gluetun v3.40+ requires control-server auth for every route. This managed
# role file re-opens only the read-only public-IP route the watchdog polls,
# and the control server listens on 127.0.0.1 inside gluetun's namespace only.
# It lives in user-owned .stremio/ (gluetun-data/ is root-owned) and is
# mounted to /gluetun/auth/config.toml through the generated override.
GLUETUN_AUTH_CONTAINER_PATH = "/gluetun/auth/config.toml"
GLUETUN_AUTH_TEMPLATE = """\
# Generated by ./stremio; do not edit by hand.
# Grants unauthenticated access to the read-only public IP route so the
# watchdog can poll gluetun's own egress view instead of external services.
[[roles]]
name = "stremioguard"
routes = ["GET /v1/publicip/ip"]
auth = "none"
"""

# Gluetun settings pinned in docker-compose.yml (D1). Kept in the same order so
# operator warnings match the table; never forwarded through .stremio/gluetun.env.
GLUETUN_PINNED_ENV: dict[str, str] = {
    "DNS_KEEP_NAMESERVER": "off",
    "FIREWALL_ENABLED_DISABLING_IT_SHOOTS_YOU_IN_YOUR_FOOT": "on",
    "HTTP_CONTROL_SERVER_ADDRESS": "127.0.0.1:18080",
    "HTTPPROXY": "off",
    "SHADOWSOCKS": "off",
    "PPROF_ENABLED": "no",
    "HEALTH_SERVER_ADDRESS": "127.0.0.1:9999",
    "HTTP_CONTROL_SERVER_AUTH_CONFIG_FILEPATH": GLUETUN_AUTH_CONTAINER_PATH,
    "HTTP_CONTROL_SERVER_AUTH_DEFAULT_ROLE": "{}",
    "FIREWALL_INPUT_PORTS": "",
    "FIREWALL_VPN_INPUT_PORTS": "",
    "FIREWALL_OUTBOUND_SUBNETS": "",
    "VPN_PORT_FORWARDING": "off",
    "VPN_INTERFACE": "tun0",
}


# Settings StremioGuard owns, as opposed to gluetun's. They never reach the
# VPN container: every StremioGuard secret (debrid keys, configure password,
# TorBox key) lives under COMET_, and gluetun has no use for any of them.
# Everything else in .env is gluetun configuration and passes through, so a
# gluetun option added to .env keeps working without a code change.
STREMIOGUARD_ENV_PREFIXES = ("COMET_", "STREMIO_")
STREMIOGUARD_ENV_KEYS = frozenset(
    {
        *TUNABLE_KEYS,
        # Interpolated into the stremio service by docker-compose.yml.
        "CASTING_DISABLED",
        "EXTERNAL_BASE_URL",
        "INTERNAL_MEDIA_BASE_URL",
    }
)


GENERATED_ENV_HEADER = "# Generated by ./stremio from .env; do not edit by hand."


def render_gluetun_env(env_text: str) -> str:
    """Gluetun's own settings from .env, parsed once and re-quoted.

    Parsed by StremioGuard's parser and written back fully quoted, so the
    key filter and the VPN container see the same keys and values: a line
    such as `export COMET_TORBOX_API_KEY=...` is filtered by its real key
    instead of slipping through as an unrecognized one.
    """
    kept = {
        key: value
        for key, value in parse_dotenv(env_text).items()
        if not key.startswith(STREMIOGUARD_ENV_PREFIXES)
        and key not in STREMIOGUARD_ENV_KEYS
        and key not in GLUETUN_PINNED_ENV
    }
    return render_dotenv(kept, header=GENERATED_ENV_HEADER)


def write_gluetun_env(root_dir: Path) -> Path:
    path = root_dir / GLUETUN_ENV_FILE
    env_file = root_dir / ".env"
    content = render_gluetun_env(env_file.read_bytes().decode("utf-8") if env_file.exists() else "")
    atomic_write_text(path, content, mode=0o600)
    return path


def ensure_gluetun_auth_config(root_dir: Path) -> Path:
    """Write the managed control-server role file, honoring user overrides."""
    path = root_dir / ".stremio" / "gluetun-auth.toml"
    if path.exists():
        content = path.read_text(encoding="utf-8")
        if "Generated by ./stremio" not in content:
            return path
        if content == GLUETUN_AUTH_TEMPLATE:
            return path
    atomic_write_text(path, GLUETUN_AUTH_TEMPLATE, mode=0o600)
    return path


def render_gluetun_ports(
    bind_addresses: list[str],
    port_mappings: list[tuple[int, int]],
    extra_lines: list[str] | None = None,
) -> str | None:
    if not bind_addresses and not extra_lines:
        return None
    lines: list[str] = []
    for address in bind_addresses:
        for host_port, container_port in port_mappings:
            lines.append(f'      - "{address}:{host_port}:{container_port}"')
    lines.extend(extra_lines or [])
    if not lines:
        return None
    return "\n".join(lines)


def render_stack_compose_override(
    *,
    bind_addresses: list[str],
    stremio_host_port: int,
    stremio_container_port: int,
    stremio_enabled: bool,
    comet_config: CometConfig | None,
    comet_gateway_config: CometGatewayConfig | None = None,
    gluetun_auth_config_file: Path | None = None,
    comet_bundle_dir: Path | None = None,
) -> str:
    port_mappings: list[tuple[int, int]] = []
    if stremio_enabled:
        port_mappings.append((stremio_host_port, stremio_container_port))
    comet_gateway_enabled = bool(comet_gateway_config and comet_gateway_config.enabled)

    extra_gluetun_ports = []
    if comet_config and comet_config.enabled:
        if comet_gateway_enabled:
            extra_gluetun_ports.append(f'      - "127.0.0.1:{comet_config.host_port}:{COMET_PORT}"')
            assert comet_gateway_config is not None
            for address in bind_addresses:
                extra_gluetun_ports.append(
                    f'      - "{address}:{comet_gateway_config.host_port}:'
                    f'{COMET_GATEWAY_CONTAINER_PORT}"'
                )
        else:
            for address in bind_addresses:
                extra_gluetun_ports.append(
                    f'      - "{address}:{comet_config.host_port}:{COMET_PORT}"'
                )

    ports = render_gluetun_ports(bind_addresses, port_mappings, extra_gluetun_ports)
    content = ["# Generated by ./stremio; do not edit by hand.", "services:", "  gluetun:"]
    if gluetun_auth_config_file is not None:
        content.extend(
            [
                "    volumes:",
                f"      - {gluetun_auth_config_file}:{GLUETUN_AUTH_CONTAINER_PATH}:ro",
            ]
        )
    if ports is None:
        content.append("    ports: []")
    else:
        content.extend(["    ports:", ports])

    if comet_gateway_enabled and comet_gateway_config:
        content.extend(
            [
                "  comet-gateway:",
                "    volumes:",
                f"      - {comet_gateway_config.state_dir}:{GATEWAY_CONFIG_DIR}:ro",
            ]
        )

    if comet_config and comet_config.enabled:
        comet_volumes = [f"      - {comet_config.data_dir}:/app/data"]
        if comet_bundle_dir is not None:
            manifest = json.loads(
                (comet_bundle_dir / BUNDLE_MANIFEST_NAME).read_text(encoding="utf-8")
            )
            for output_name, container_path in manifest.get("outputs", {}).items():
                comet_volumes.append(
                    f"      - {comet_bundle_dir / output_name}:{container_path}:ro"
                )
        content.extend(
            [
                "  comet:",
                f"    image: {comet_config.image}",
                "    env_file:",
                f"      - {comet_config.runtime_env_file}",
                "    volumes:",
                *comet_volumes,
                "    healthcheck:",
                f"      interval: {comet_config.healthcheck_interval_seconds}s",
                "      timeout: 5s",
                "      retries: 5",
                "      start_period: 10s",
            ]
        )
        # comet-postgres is deliberately absent: its env_file and data
        # directory are fixed paths, so they live in docker-compose.yml where
        # every way of starting the stack picks them up. Generating them here
        # meant a plain `docker compose up` started Postgres against an
        # anonymous volume.

    return "\n".join(content) + "\n"


BUNDLE_MANIFEST_NAME = "bundle-manifest.json"


class StackPublisher:
    """Single owner of the published generation: what the stack runs from.

    A publish reads .env and docker-compose.yml once and writes, under
    .stremio/: gluetun's env file, a normalized snapshot of .env, a copy of
    the base compose file, and the generated override. Every compose call
    and the watchdog then use those files (config.compose_command), so the
    working tree can change without changing the running stack. Only
    deliberate lifecycle commands publish; the watchdog never does.
    """

    def __init__(
        self,
        root_dir: Path,
        override_file: Path | None = None,
        *,
        env_file: Path | None = None,
    ) -> None:
        """``env_file`` is the configuration to render from.

        .env (the default) is a deploy: the whole generation is rewritten.
        Any other file, in practice the published snapshot, re-renders only
        the override, for commands that change one thing about the running
        stack (the Comet image) and must not deploy unrelated pending edits.
        """
        self.root_dir = root_dir
        self.env_file = env_file or root_dir / ".env"
        self.deploying = self.env_file == root_dir / ".env"
        self.compose_override_file = override_file or root_dir / GENERATED_COMPOSE_FILE

    def publish(self, *, image_override: str | None = None) -> None:
        """Gather all config parameters, render the compose override, and write it atomically."""
        # 1. Gather bind addresses
        bind_addresses = parse_bind_addresses(self.env_file)

        # 2. Gather Stremio config parameters
        stremio_enabled = env_flag_enabled("STREMIO_ENABLED", True, env_path=self.env_file)
        stremio_host_port = env_int_value(
            self.env_file, "STREMIO_HOST_PORT", DEFAULT_STREMIO_HOST_PORT, minimum=1, maximum=65535
        )
        stremio_container_port = env_int_value(
            self.env_file,
            "STREMIO_CONTAINER_PORT",
            DEFAULT_STREMIO_CONTAINER_PORT,
            minimum=1,
            maximum=65535,
        )

        # 3. Gather Comet & Gateway configs
        comet_config = CometConfig.from_env(self.root_dir, env_file=self.env_file)
        comet_gateway_config = CometGatewayConfig.from_env(self.root_dir, env_file=self.env_file)

        # 4. Digest-pin the Comet image: never render a floating tag. Deferred
        # import to avoid a circular import (publishing -> comet.__init__ ->
        # manager -> publishing).
        comet_bundle_dir: Path | None = None
        if comet_config.enabled:
            if image_override is None:
                from stremioguard.comet.state import STATE_FILE_NAME, CometState

                comet_state = CometState.load(comet_config.state_dir / STATE_FILE_NAME)
                if not comet_state.active_digest:
                    # Never render Comet from a floating tag; `prepare_runtime`
                    # bootstraps a validated digest before anything publishes.
                    raise RuntimeError(
                        "No validated Comet image digest is recorded. Run `./stremio start` "
                        "(or `./stremio comet install`) to bootstrap one."
                    )
                image_override = f"{comet_config.image}@{comet_state.active_digest}"
            if "@" not in image_override:
                raise RuntimeError(
                    f"Refusing to publish Comet image {image_override!r} without a digest."
                )
            active_digest = image_override.rsplit("@", 1)[1]
            # Fail closed: the image and the patches mounted over it must be
            # the pair that was validated together. A missing bundle means
            # prepare_runtime never ran; a bundle for another digest means a
            # promotion stopped halfway.
            comet_bundle_dir = comet_config.bundle_dir(active_digest)
            self._require_valid_manifest(
                comet_bundle_dir,
                active_digest=active_digest,
                gateway_enabled=comet_gateway_config.enabled,
            )
            comet_config = dataclasses.replace(comet_config, image=image_override)

        # 5. Render every output before writing any file so a refusal leaves
        # the previous generation byte-identical on disk.
        gluetun_env_content: str | None = None
        snapshot_content: str | None = None
        base_compose_content: str | None = None
        parsed_env: dict[str, str] | None = None
        if self.deploying:
            env_text = self.env_file.read_bytes().decode("utf-8") if self.env_file.exists() else ""
            parsed_env = parse_dotenv(env_text, source=str(self.env_file))
            gluetun_env_content = render_gluetun_env(env_text)
            snapshot_content = render_dotenv(
                parsed_env,
                header=GENERATED_ENV_HEADER,
            )
            base_compose = self.root_dir / "docker-compose.yml"
            if base_compose.exists():
                base_compose_content = (
                    "# Published copy of docker-compose.yml; do not edit by hand.\n"
                    + base_compose.read_text(encoding="utf-8")
                )

        auth_config_file = self.root_dir / ".stremio" / "gluetun-auth.toml"
        content = render_stack_compose_override(
            bind_addresses=bind_addresses,
            stremio_host_port=stremio_host_port,
            stremio_container_port=stremio_container_port,
            stremio_enabled=stremio_enabled,
            comet_config=comet_config if comet_config.enabled else None,
            comet_gateway_config=(
                comet_gateway_config
                if comet_config.enabled and comet_gateway_config.enabled
                else None
            ),
            gluetun_auth_config_file=auth_config_file,
            comet_bundle_dir=comet_bundle_dir,
        )

        # Warn once per overridden pin after every output renders and before writing.
        if self.deploying:
            assert parsed_env is not None
            for key, pin in GLUETUN_PINNED_ENV.items():
                if key in parsed_env and parsed_env[key] != pin:
                    pin_display = pin or '""'
                    message = (
                        f".env sets {key}, but docker-compose.yml pins it to `{pin_display}` "
                        "for gluetun, so that line has no effect. Remove it from .env."
                    )
                    if key == "FIREWALL_OUTBOUND_SUBNETS":
                        message += " LAN access from the VPN namespace is not supported."
                    logger.warning("{}", message)

        # 6. Write the generation, each file atomically and the override last:
        # compose_command only switches to the published base file and env
        # snapshot once all three exist.
        ensure_gluetun_auth_config(self.root_dir)
        if self.deploying:
            assert gluetun_env_content is not None
            assert snapshot_content is not None
            atomic_write_text(self.root_dir / GLUETUN_ENV_FILE, gluetun_env_content, mode=0o600)
            atomic_write_text(self.root_dir / PUBLISHED_ENV_FILE, snapshot_content, mode=0o600)
            if base_compose_content is not None:
                atomic_write_text(
                    self.root_dir / PUBLISHED_COMPOSE_FILE,
                    base_compose_content,
                    mode=0o600,
                )
        atomic_write_text(self.compose_override_file, content, mode=0o600)
        # Last: the hashes of the generation just written. Until this lands, a
        # publish cut short leaves files that do not match the previous
        # manifest, and the watchdog refuses to start containers from them.
        atomic_write_text(
            self.root_dir / PUBLISHED_GENERATION_FILE,
            render_generation_manifest(self.root_dir),
            mode=0o600,
        )

    def _require_valid_manifest(
        self, bundle_dir: Path, *, active_digest: str, gateway_enabled: bool
    ) -> None:
        manifest_path = bundle_dir / BUNDLE_MANIFEST_NAME
        if not manifest_path.exists():
            raise RuntimeError(
                f"Comet is enabled but no override bundle exists for image {active_digest} "
                f"(expected {manifest_path}). Run `./stremio restart` (or `./stremio comet "
                "install`) to render the managed patches before publishing the stack."
            )
        try:
            manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            raise RuntimeError(
                f"Comet override bundle manifest at {manifest_path} is unreadable "
                f"({error}). Re-run `./stremio comet install` to regenerate it."
            ) from error
        if not isinstance(manifest, dict) or manifest.get("active_digest") != active_digest:
            recorded = manifest.get("active_digest") if isinstance(manifest, dict) else None
            raise RuntimeError(
                f"Comet override bundle at {bundle_dir} was rendered for image "
                f"{recorded or 'an unknown digest'}, not the active {active_digest}. Mounting "
                "one image's patches over another is refused. Run `./stremio restart` to "
                "render the bundle for the active image."
            )
        outputs = manifest.get("outputs", {})
        missing = [
            name
            for name in required_output_names(gateway_enabled=gateway_enabled)
            if name not in outputs
        ]
        if missing:
            raise RuntimeError(
                "Comet override bundle is missing patches required by this deployment "
                f"shape: {', '.join(sorted(missing))}. Starting anyway would drop a "
                "safety or privacy guarantee (P2P block, secret redaction, gateway "
                "URLs). Fix the patch compatibility (see `./stremio comet install` "
                "output) before starting."
            )
        # Docker creates a directory at a missing bind-mount source, and Comet
        # would then import a directory instead of its patched module.
        absent = [name for name in outputs if not (bundle_dir / name).is_file()]
        if absent:
            raise RuntimeError(
                f"Comet override bundle at {bundle_dir} lists files that are missing on "
                f"disk: {', '.join(sorted(absent))}. Run `./stremio restart` to re-render it."
            )
